/// Cell index for a character; unknown characters draw as `?`.
pub fn cellFor(ch: u8) usize {
    const up = std.ascii.toUpper(ch);
    if (up >= 32 and up <= 95) return up - 32;
    return '?' - 32;
}

/// The atlas as RGBA8 (white, coverage in alpha).
pub fn buildAtlas(out: *[atlas_w * atlas_h * 4]u8) void {
    @memset(out, 0);
    for (0..64) |ci| {
        const cx = (ci % cols) * cell;
        const cy = (ci / cols) * cell;
        for (0..7) |row| {
            const bits = glyphs[ci][row];
            for (0..5) |col| {
                if (bits & (@as(u8, 0x10) >> @intCast(col)) != 0) setPixel(out, cx + col, cy + row);
            }
        }
    }
    // Solid block, kept clear of the edge so linear filtering cannot leak.
    const sx = (solid_cell % cols) * cell;
    const sy = (solid_cell / cols) * cell;
    for (0..cell) |y| for (0..cell) |x| setPixel(out, sx + x, sy + y);
}

fn setPixel(out: *[atlas_w * atlas_h * 4]u8, x: usize, y: usize) void {
    const o = (y * atlas_w + x) * 4;
    out[o] = 255;
    out[o + 1] = 255;
    out[o + 2] = 255;
    out[o + 3] = 255;
}

test "atlas has glyph pixels where expected" {
    var atlas: [atlas_w * atlas_h * 4]u8 = undefined;
    buildAtlas(&atlas);
    // 'I' (cell 41): top row 0x0E -> columns 1..3 set, column 0 clear.
    const ci = cellFor('I');
    try std.testing.expectEqual(@as(usize, 'I' - 32), ci);
    const x0 = (ci % cols) * cell;
    const y0 = (ci / cols) * cell;
    try std.testing.expectEqual(@as(u8, 0), atlas[(y0 * atlas_w + x0) * 4 + 3]);
    try std.testing.expectEqual(@as(u8, 255), atlas[(y0 * atlas_w + x0 + 2) * 4 + 3]);
    // space is empty; solid block is full
    var any = false;
    for (0..cell * cell) |i| {
        const x = i % cell;
        const y = i / cell;
        if (atlas[(y * atlas_w + x) * 4 + 3] != 0) any = true;
    }
    try std.testing.expect(!any);
    const sx = (solid_cell % cols) * cell;
    const sy = (solid_cell / cols) * cell;
    try std.testing.expectEqual(@as(u8, 255), atlas[((sy + 7) * atlas_w + sx + 7) * 4 + 3]);
    // lowercase maps to uppercase
    try std.testing.expectEqual(cellFor('a'), cellFor('A'));
}
