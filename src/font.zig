//! A tiny built-in bitmap font so the engine can show text without shipping
//! any font file. Glyphs are 5x7 pixels for ASCII 32..95 (lowercase letters
//! draw as uppercase). They are drawn from an 8x9 grid of 8x8 cells packed
//! into one RGBA atlas; the last cell is a solid block used for rectangles.

const std = @import("std");

pub const cell = 8;
pub const cols = 8;
pub const rows = 9;
pub const atlas_w = cols * cell;
pub const atlas_h = rows * cell;
/// Cell index of the solid block.
pub const solid_cell = 64;

